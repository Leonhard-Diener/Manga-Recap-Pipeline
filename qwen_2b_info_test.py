#!/usr/bin/env python3

"""
Fast Qwen3.5-2B manga page description.

One complete manga page is analyzed in one inference.

The model outputs plain text:
    PANEL 1: ...
    PANEL 2: ...

The Python program converts this into JSON.

No detections.json is required.
No JSON is generated by the model.
"""

from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path

os.environ["TOKENIZERS_PARALLELISM"] = "false"

import torch
from transformers import AutoModelForMultimodalLM, AutoProcessor


# ============================================================
# Configuration
# ============================================================

MODEL_PATH = Path("./models/Qwen3.5-2B")

PAGE_DIRECTORY = Path(
    "./output/"
    "Maou-sama no Machizukuri! ~Saikyou no Dungeon wa Kindai Toshi~/"
    "chapter_075/page_previews"
)

OUTPUT_FILE = Path("./page_descriptions.json")

SUPPORTED_EXTENSIONS = {
    ".jpg",
    ".jpeg",
    ".png",
    ".webp",
}

# Lower image resolution reduces vision-side computation.
MIN_PIXELS = 256 * 28 * 28
MAX_PIXELS = 384 * 28 * 28

# Hard output limit.
#
# Keep this deliberately low. The target is short descriptions,
# not long prose.
MAX_NEW_TOKENS = 48

# Qwen3.5 should not use its reasoning mode for this task.
ENABLE_THINKING = True

# Deterministic generation avoids sampling overhead and makes
# output easier to parse.
DO_SAMPLE = False

# KV cache is essential for efficient autoregressive generation.
USE_CACHE = True

# Static cache + torch.compile is intentionally disabled here.
#
# On your GTX 1080 this previously triggered an undesirable
# TorchInductor/autotuning path.
USE_STATIC_CACHE = False

# Warmup removes most first-call CUDA initialization overhead.
ENABLE_WARMUP = True


# ============================================================
# Prompt
# ============================================================

PAGE_PROMPT = """\
Analyze the image visually.

For each panel, output:
PANEL N:
Characters: ...
Location: ...
Actions: ...

Rules:
- Describe every visible character or creature.
- Describe their visible appearance briefly.
- Describe where the scene takes place.
- Describe exactly what each character is visibly doing.
- Describe important visible objects when relevant.
- Use only information directly visible in the image.
- Do not guess names, identities, relationships, intentions, or story context.
- Do not invent events.
- Do not infer what happened before or after the scene.
- Only quote text that is clearly readable.
- Keep each field concise.
- No reasoning.
- No JSON.
"""


# ============================================================
# Page discovery
# ============================================================

def natural_sort_key(path: Path) -> list[object]:
    """Sort filenames naturally."""

    return [
        int(part) if part.isdigit() else part.lower()
        for part in re.split(r"(\d+)", path.name)
    ]


def get_pages(directory: Path) -> list[Path]:
    """Return all supported page images in natural order."""

    if not directory.is_dir():
        raise FileNotFoundError(
            f"Page directory does not exist: {directory}"
        )

    pages = [
        path
        for path in directory.iterdir()
        if path.is_file()
        and path.suffix.lower() in SUPPORTED_EXTENSIONS
    ]

    return sorted(
        pages,
        key=natural_sort_key,
    )


# ============================================================
# Model loading
# ============================================================

def load_model():
    """Load the processor and Qwen3.5-2B in FP16."""

    if not torch.cuda.is_available():
        raise RuntimeError(
            "CUDA is not available."
        )

    # No TF32 benefit on GTX 1080/Pascal.
    torch.backends.cuda.matmul.allow_tf32 = False

    processor = AutoProcessor.from_pretrained(
        MODEL_PATH,
        min_pixels=MIN_PIXELS,
        max_pixels=MAX_PIXELS,
    )

    model = (
        AutoModelForMultimodalLM
        .from_pretrained(
            MODEL_PATH,
            device_map="auto",
            dtype=torch.float16,
        )
        .eval()
    )

    return processor, model


# ============================================================
# Tensor preparation
# ============================================================

def move_to_device(
    inputs,
    device: torch.device,
):
    """Move processor tensors directly to CUDA."""

    for key, value in inputs.items():

        if not torch.is_tensor(value):
            continue

        if value.is_floating_point():
            inputs[key] = value.to(
                device=device,
                dtype=torch.float16,
                non_blocking=True,
            )
        else:
            inputs[key] = value.to(
                device=device,
                non_blocking=True,
            )

    return inputs


# ============================================================
# Warmup
# ============================================================

def warmup(
    processor,
    model,
) -> None:
    """Initialize CUDA/model kernels before real inference."""

    if not ENABLE_WARMUP:
        return

    messages = [
        {
            "role": "user",
            "content": [
                {
                    "type": "text",
                    "text": "Reply with exactly: OK",
                }
            ],
        }
    ]

    inputs = processor.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=True,
        return_dict=True,
        return_tensors="pt",
        enable_thinking=ENABLE_THINKING,
    )

    inputs = move_to_device(
        inputs,
        model.device,
    )

    with torch.inference_mode():
        model.generate(
            **inputs,
            max_new_tokens=2,
            do_sample=False,
            use_cache=True,
        )

    torch.cuda.synchronize()


# ============================================================
# Response parsing
# ============================================================

PANEL_PATTERN = re.compile(
    r"^\s*PANEL\s+(\d+)\s*:\s*(.+?)\s*$",
    re.IGNORECASE | re.MULTILINE,
)


def parse_response(
    response: str,
) -> dict[int, str]:
    """Extract PANEL N: description lines."""

    descriptions: dict[int, str] = {}

    for match in PANEL_PATTERN.finditer(response):

        panel_number = int(
            match.group(1)
        )

        description = " ".join(
            match.group(2).split()
        ).strip()

        if description:
            descriptions[
                panel_number
            ] = description

    return descriptions


# ============================================================
# Page inference
# ============================================================

def describe_page(
    page_path: Path,
    processor,
    model,
) -> tuple[dict[int, str], float, int, str]:
    """
    Describe every visible panel on one page.

    Returns:
        descriptions,
        generation_time,
        generated_tokens,
        raw_response
    """

    messages = [
        {
            "role": "user",
            "content": [
                {
                    "type": "image",
                    "image": str(
                        page_path.resolve()
                    ),
                },
                {
                    "type": "text",
                    "text": PAGE_PROMPT,
                },
            ],
        }
    ]

    # --------------------------------------------------------
    # Build native Qwen3.5 multimodal input.
    # --------------------------------------------------------

    inputs = processor.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=True,
        return_dict=True,
        return_tensors="pt",
        enable_thinking=ENABLE_THINKING,
    )

    inputs = move_to_device(
        inputs,
        model.device,
    )

    # --------------------------------------------------------
    # Synchronize before timing.
    # --------------------------------------------------------

    torch.cuda.synchronize()

    start = time.perf_counter()

    # --------------------------------------------------------
    # Generation.
    # --------------------------------------------------------

    with torch.inference_mode():

        output_ids = model.generate(
            **inputs,
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=DO_SAMPLE,
            num_beams=1,
            use_cache=USE_CACHE,
            eos_token_id=(
                processor.tokenizer.eos_token_id
            ),
            pad_token_id=(
                processor.tokenizer.pad_token_id
            ),
        )

    torch.cuda.synchronize()

    elapsed = (
        time.perf_counter()
        - start
    )

    # --------------------------------------------------------
    # Decode only generated tokens.
    # --------------------------------------------------------

    input_length = int(
        inputs["input_ids"].shape[-1]
    )

    generated_ids = output_ids[
        0,
        input_length:
    ]

    generated_tokens = int(
        generated_ids.shape[-1]
    )

    response = processor.decode(
        generated_ids,
        skip_special_tokens=True,
    ).strip()

    descriptions = parse_response(
        response
    )

    return (
        descriptions,
        elapsed,
        generated_tokens,
        response,
    )


# ============================================================
# Main processing
# ============================================================

def main() -> None:

    print("=" * 70)
    print("QWEN3.5-2B FAST MANGA DESCRIPTION")
    print("=" * 70)

    # --------------------------------------------------------
    # Find pages.
    # --------------------------------------------------------

    pages = get_pages(
        PAGE_DIRECTORY
    )

    if not pages:
        raise RuntimeError(
            f"No page images found in {PAGE_DIRECTORY}"
        )

    print(
        f"Pages: {len(pages)}",
        flush=True,
    )

    # --------------------------------------------------------
    # Load model.
    # --------------------------------------------------------

    print(
        "\nLoading model...",
        flush=True,
    )

    processor, model = load_model()

    print(
        f"GPU: {torch.cuda.get_device_name(0)}",
        flush=True,
    )

    print(
        f"CUDA: {torch.version.cuda}",
        flush=True,
    )

    print(
        f"Device: {model.device}",
        flush=True,
    )

    print(
        f"Dtype: {next(model.parameters()).dtype}",
        flush=True,
    )

    # --------------------------------------------------------
    # Warmup.
    # --------------------------------------------------------

    warmup(
        processor,
        model,
    )

    print(
        "Warmup complete.",
        flush=True,
    )

    # --------------------------------------------------------
    # Process pages.
    # --------------------------------------------------------

    results: dict[str, dict] = {}

    total_start = time.perf_counter()

    total_generation_time = 0.0
    total_tokens = 0

    for index, page_path in enumerate(
        pages,
        start=1,
    ):

        print(
            f"\nPage {index}/{len(pages)}: "
            f"{page_path.name}",
            flush=True,
        )

        (
            descriptions,
            elapsed,
            generated_tokens,
            raw_response,
        ) = describe_page(
            page_path,
            processor,
            model,
        )

        print(
            f"    Generate: {elapsed:.2f}s",
            flush=True,
        )

        print(
            f"    Tokens:   {generated_tokens}/{MAX_NEW_TOKENS}",
            flush=True,
        )

        print(
            f"    Panels:   {len(descriptions)}",
            flush=True,
        )

        # ----------------------------------------------------
        # Print descriptions.
        # ----------------------------------------------------

        for panel_number in sorted(
            descriptions
        ):

            print(
                f"    Panel {panel_number}: "
                f"{descriptions[panel_number]}",
                flush=True,
            )

        # ----------------------------------------------------
        # Show raw output only when parsing failed.
        # ----------------------------------------------------

        if not descriptions:

            print(
                f"    Raw output: {raw_response!r}",
                flush=True,
            )

        # ----------------------------------------------------
        # Store result.
        # ----------------------------------------------------

        results[
            page_path.name
        ] = {
            "panels": [
                {
                    "panel_number": number,
                    "description": descriptions[number],
                }
                for number in sorted(
                    descriptions
                )
            ],
            "generation_time": elapsed,
            "generated_tokens": generated_tokens,
        }

        total_generation_time += elapsed
        total_tokens += generated_tokens

    # --------------------------------------------------------
    # Save JSON.
    # --------------------------------------------------------

    with OUTPUT_FILE.open(
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            results,
            file,
            indent=2,
            ensure_ascii=False,
        )

    # --------------------------------------------------------
    # Statistics.
    # --------------------------------------------------------

    total_elapsed = (
        time.perf_counter()
        - total_start
    )

    average_time = (
        total_generation_time
        / len(pages)
    )

    average_tokens = (
        total_tokens
        / len(pages)
    )

    print(
        "\n" + "=" * 70,
        flush=True,
    )

    print(
        "COMPLETE",
        flush=True,
    )

    print(
        "=" * 70,
        flush=True,
    )

    print(
        f"Average generation: {average_time:.2f}s/page",
        flush=True,
    )

    print(
        f"Average tokens:     {average_tokens:.1f}",
        flush=True,
    )

    print(
        f"Total runtime:      {total_elapsed:.2f}s",
        flush=True,
    )

    print(
        f"Output:             {OUTPUT_FILE.resolve()}",
        flush=True,
    )


if __name__ == "__main__":
    main()